//! A single-line text input on GPUI's input-handler API (IME, selection, clipboard, Czech diacritics).
//!
//! Carried over from the GPUI spike, which built it on GPUI's `input` example and verified typing,
//! composition and paste. Colours come from the theme via [`InputColors`]; the font is the parent's.

