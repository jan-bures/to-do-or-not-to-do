import { expect, test } from "@playwright/test";
import { open, watch } from "./helpers.mjs";

test.use({ viewport: { width: 1440, height: 900 } });
const task = (page, name = "Review the API latency report") => page.getByRole("button", { name, exact: true });
const detail = (page) => page.locator("#task-detail");
const undo = (page) => page.locator(".toast").getByRole("button", { name: /^Undo/ });
const room = (page, name) => page.locator(".sidebar").getByRole("link", { name: new RegExp(`^${name}( |$)`) });
const action = (page, name) => page.getByRole("menuitem", { name, exact: true });
const dialog = (page, name) => page.getByRole("dialog", { name, exact: true });

test("repeat presets set the first date atomically; clearing repeat keeps its due date", async ({ page }) => {
  const w = watch(page);
  await open(page);
  await task(page).click();
  const repeat = detail(page).getByRole("button", { name: "Repeat", exact: true });
  const due = detail(page).getByRole("button", { name: /^Edit due date:/ });
  await expect(repeat).toHaveText("Does not repeat");
  await expect(due).toHaveText("Set date");
  await page.keyboard.press("r");
  const picker = dialog(page, "Repeat");
  const rules = picker.getByRole("listbox", { name: "Repeat" });
  await expect(rules.getByRole("option", { name: /^Weekly on/ })).toBeVisible();
  await expect(rules.getByRole("option", { name: /^Monthly on day/ })).toBeVisible();
  await expect(rules.getByRole("option", { name: "Yearly" })).toBeVisible();
  const off = rules.getByRole("option", { name: "Don’t repeat", selected: true });
  await expect(off).toBeFocused();
  await expect(picker).toContainText("Due starts today or on the next matching day.");
  await page.keyboard.press("Home");
  await page.keyboard.press("ArrowDown");
  await expect(rules.getByRole("option", { name: "Weekdays" })).toBeFocused();
  await expect(off).toHaveAttribute("aria-selected", "true");
  await page.keyboard.press("Enter");
  await expect(repeat).toBeFocused();
  await expect(repeat).toHaveText("Every weekday");
  // Saturday fixture: first matching date is Monday.
  await due.click();
  const date = detail(page).getByRole("textbox", { name: "Due date" });
  await expect(date).toHaveValue("2026-11-23");
  await date.press("Escape");
  await expect(due).toBeFocused();
  await page.keyboard.press("Control+z");
  await expect(repeat).toHaveText("Does not repeat");
  await expect(due).toHaveText("Set date");
  await repeat.click();
  await picker.getByRole("option", { name: "Daily" }).click();
  await repeat.click();
  await picker.getByRole("option", { name: "Don’t repeat" }).click();
  await expect(repeat).toHaveText("Does not repeat");
  await expect(due).not.toHaveText("Set date");
  await w.check();
});

test("custom repeat validates the interval and the selected weekdays; Escape discards the draft", async ({ page }) => {
  const w = watch(page);
  await open(page);
  await task(page).click();
  const repeat = detail(page).getByRole("button", { name: "Repeat", exact: true });
  const openCustom = async () => {
    await repeat.click();
    await dialog(page, "Repeat").getByRole("option", { name: "Custom…" }).click();
    return dialog(page, "Custom repeat");
  };
  const custom = await openCustom();
  const interval = custom.getByRole("spinbutton", { name: "Interval" });
  await expect(interval).toBeFocused();
  await interval.fill("0");
  const apply = custom.getByRole("button", { name: "Apply repeat" });
  await expect(apply).toBeDisabled();
  await expect(custom.getByRole("status")).toContainText("Choose an interval from 1 to 999");
  await interval.fill("2");
  await custom.getByRole("combobox", { name: "Unit" }).selectOption("Week");
  await custom.getByRole("button", { name: "Saturday" }).click();
  await expect(custom.getByRole("status")).toHaveText("Choose at least one weekday.");
  await custom.getByRole("button", { name: "Tuesday" }).click();
  await custom.getByRole("button", { name: "Thursday" }).click();
  await expect(custom.getByRole("status")).toContainText("Every 2 weeks on Tue, Thu. Due will be 1 Dec 2026.");
  await apply.click();
  await expect(repeat).toHaveText("Every 2 weeks on Tue, Thu");
  await openCustom();
  await expect(interval).toHaveValue("2");
  await expect(custom.getByRole("button", { name: "Thursday" })).toHaveAttribute("aria-pressed", "true");
  await interval.fill("3");
  await interval.press("Escape");
  await expect(repeat).toHaveText("Every 2 weeks on Tue, Thu");
  await expect(repeat).toBeFocused();
  await w.check();
});

test("pick tags by name, manage them, and undo through the shared change path", async ({ page }) => {
  const w = watch(page);
  await open(page);
  await task(page).click();
  await page.keyboard.press("t");
  const picker = dialog(page, "Tags");
  const filter = picker.getByRole("textbox", { name: "Type to find or create a tag" });
  await expect(filter).toBeFocused();
  await filter.fill("DOCS");
  await expect(picker.getByRole("button", { name: /Create tag/ })).toHaveCount(0);
  await filter.press("ArrowDown");
  const docs = picker.getByRole("button", { name: "docs", exact: true });
  await expect(docs).toBeFocused();
  await docs.press("Enter");
  await expect(docs).toBeFocused();
  await expect(docs).toHaveAttribute("aria-pressed", "true");
  await docs.press("Enter");
  await expect(docs).toHaveAttribute("aria-pressed", "false");
  await docs.press("Control+z");
  const tags = detail(page).getByRole("button", { name: "Tags", exact: true });
  await expect(tags).toContainText("docs");
  await expect(tags).toHaveAccessibleDescription("docs, ops");

  await tags.click();
  await filter.fill("x".repeat(1001));
  await filter.press("Enter");
  await expect(picker.getByRole("alert")).toContainText("Couldn't create that tag: a tag's name can be at most");
  await filter.fill("Web Organize");
  await expect(picker.getByRole("button", { name: "Create tag “Web Organize”" })).toBeVisible();
  await filter.press("Enter");
  await expect(tags).toContainText("Web Organize");
  const manage = () => page.getByRole("button", { name: "Manage tag “Web Organize”" });
  await manage().click();
  await page.getByRole("button", { name: "Rename tag", exact: true }).click();
  const rename = dialog(page, "Rename tag");
  const name = rename.getByRole("textbox", { name: "Tag name" });
  await expect(name).toBeFocused();
  await name.fill("DOCS");
  await name.press("Enter");
  await expect(rename.getByRole("alert")).toHaveText("Couldn't rename that tag: there is already a tag named “docs”.");
  await name.fill("Organized");
  await name.press("Enter");
  await expect(tags).toBeFocused();
  await expect(tags).toContainText("Organized");

  const edit = async () => {
    await tags.click();
    const choice = picker.getByRole("button", { name: "Organized", exact: true });
    await choice.press("ArrowRight");
  };
  await edit();
  await page.getByRole("button", { name: "Colour…", exact: true }).click();
  const swatches = dialog(page, "Tag colour").getByRole("listbox", { name: "Colour swatches" });
  await expect(swatches.getByRole("option")).toHaveCount(12);
  const fern = swatches.getByRole("option", { name: "Fern", exact: true });
  await expect(swatches.getByRole("option", { selected: true })).toBeFocused();
  await page.keyboard.press("Home");
  await expect(swatches.getByRole("option", { name: "Rose" })).toBeFocused();
  await page.keyboard.press("ArrowDown");
  await expect(swatches.getByRole("option", { name: "Teal" })).toBeFocused();
  await fern.click();
  await expect(tags.locator(".detail-tag").filter({ hasText: "Organized" })).toHaveAttribute("data-list-hue", "fern");
  await edit();
  await page.getByRole("button", { name: "Delete tag…" }).click();
  const confirm = dialog(page, "Delete tag");
  await expect(confirm).toContainText("It’s on 1 task. The task stays.");
  await expect(confirm.getByRole("button", { name: "Cancel" })).toBeFocused();
  await confirm.getByRole("button", { name: "Delete tag", exact: true }).click();
  await expect(tags).not.toContainText("Organized");
  await undo(page).click();
  await expect(tags).toContainText("Organized");
  await w.check();
});

test("links validate shared addresses, keep the draft on refusal, and support exact Undo", async ({ page }) => {
  const w = watch(page);
  await open(page);
  await task(page).click();
  await page.keyboard.press("l");
  const input = detail(page).getByRole("textbox", { name: "Add a web link" });
  await expect(input).toBeFocused();
  await input.fill("not an address");
  await input.press("Enter");
  await expect(detail(page).getByRole("alert")).toContainText("isn't a web address");
  await expect(input).toHaveValue("not an address");
  await input.press("t");
  await input.press("r");
  await expect(dialog(page, "Tags")).toBeHidden();
  await expect(dialog(page, "Repeat")).toBeHidden();
  for (const text of ["javascript:void(0)", "data:text/plain,example"]) {
    await input.fill(text);
    await input.press("Enter");
    await expect(detail(page).getByRole("alert")).toContainText("isn't a web address");
    await expect(input).toHaveValue(text);
    await expect(detail(page).locator('a[href^="javascript:"], a[href^="data:"]')).toHaveCount(0);
  }
  await input.fill("example.com/organize");
  await input.press("Enter");
  const link = detail(page).locator('a[href="https://example.com/organize"]');
  await expect(link).toBeVisible();
  await detail(page).getByRole("button", { name: /Remove link/ }).click();
  await expect(link).toHaveCount(0);
  await expect(input).toBeFocused();
  await undo(page).click();
  await expect(link).toBeVisible();
  await w.check();
});

