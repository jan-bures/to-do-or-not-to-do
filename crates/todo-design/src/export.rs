//! Generators for the checked-in exports in `crates/todo-design/generated/`:
//!
//! - [`css()`] → `tokens.css`: custom properties for the web client.
//! - [`json()`] → `tokens.json`: everything, for Compose (or any other consumer that can't call Rust).
//!
//! Both are pure functions of the token tables. A test fails when the checked-in files are stale; regenerate them
//! with `TODO_DESIGN_BLESS=1 cargo test -p todo-design --test generated`.

use std::fmt::Write as _;

use serde_json::{Map, Value, json};

use crate::chrome;
use crate::color::{Rgb, Rgba};
use crate::fonts;
use crate::hues::{self, NamedHue};
use crate::icons::{Glyph, Icon};
use crate::landscape;
use crate::layout::{component, desktop, elevation, phone, radius, space};
use crate::motion;
use crate::palette::{
    AgentColors, Dusk, GUARD_STEP, GUARDS, LIST_DARK_HUE_SHIFT, LIST_ON_STRONG_DARK, ListColors,
    Palette, ROOM_DARK_HUE_SHIFT, Spec, Theme, agent_colors, dusk, list_colors, palette,
};
use crate::typography::{self, TextStyle};

const HEADER: &str = "Generated by todo-design (crates/todo-design/src/export.rs). Do not edit by hand.\n\
Regenerate with: TODO_DESIGN_BLESS=1 cargo test -p todo-design --test generated";

/// Landscape sizes, strokes and opacities, for the exports.
const LANDSCAPE: [(&str, f32); 12] = [
    ("height-desktop", landscape::HEIGHT_DESKTOP),
    ("height-cover", landscape::HEIGHT_COVER),
    ("height-inner", landscape::HEIGHT_INNER),
    ("height-finished", landscape::HEIGHT_FINISHED),
    ("arc-stroke", landscape::ARC_STROKE),
    ("travelled-stroke", landscape::TRAVELLED_STROKE),
    (
        "travelled-stroke-finished",
        landscape::TRAVELLED_STROKE_FINISHED,
    ),
    ("ray-stroke", landscape::RAY_STROKE),
    ("ring-stroke", landscape::RING_STROKE),
    ("halo-opacity", landscape::HALO_OPACITY),
    ("star-opacity", landscape::STAR_OPACITY),
    ("moon-opacity", landscape::MOON_OPACITY),
];

fn shadows(theme: Theme) -> &'static [elevation::Shadow; 2] {
    match theme {
        Theme::Light => &elevation::OVERLAY_LIGHT,
        Theme::Dark => &elevation::OVERLAY_DARK,
    }
}

fn css_shadow(theme: Theme) -> String {
    shadows(theme)
        .iter()
        .map(|s| format!("0 {}px {}px {}px {}", s.y, s.blur, s.spread, s.color.css()))
        .collect::<Vec<_>>()
        .join(", ")
}

fn css_font(style: &TextStyle) -> String {
    let var = match style.family {
        typography::DISPLAY => "--font-display",
        typography::DISPLAY_TEXT => "--font-display-text",
        typography::MONO => "--font-mono",
        _ => "--font-ui",
    };
    format!(
        "{}{} {}px/{}px var({var})",
        if style.italic { "italic " } else { "" },
        style.weight,
        style.size,
        style.line_height
    )
}

fn css_block(out: &mut String, selector: &str, vars: &[(String, String)]) {
    let _ = writeln!(out, "{selector} {{");
    for (k, v) in vars {
        let _ = writeln!(out, "  --{k}: {v};");
    }
    out.push_str("}\n\n");
}

fn color_vars(prefix: &str, entries: Vec<(&'static str, Rgb)>) -> Vec<(String, String)> {
    entries
        .into_iter()
        .map(|(n, c)| (format!("{prefix}-{n}"), c.hex()))
        .collect()
}

/// `tokens.css`: custom properties for the web client.
///
/// - `:root` holds fonts, type, spacing, radii, motion and metrics.
/// - `[data-theme="light|dark"][data-room-hue="<key>"]` holds a room's `--color-*` palette.
/// - `[data-room-hue="<key>"]` holds the finished scene's `--dusk-*` colours (the same in both themes).
/// - `[data-list-hue="<key>"]` and `[data-agent="<key>"]` inside a theme hold `--list-*` and `--agent-*`.
///
/// Fonts are expected at `fonts/` next to the stylesheet.
pub fn css() -> String {
    let mut out = String::new();
    let _ = writeln!(out, "/* {} */\n", HEADER.replace('\n', "\n   "));

    for f in fonts::FACES {
        let _ = writeln!(
            out,
            "@font-face {{\n  font-family: \"{}\";\n  src: url(\"fonts/{}\") format(\"truetype\");\n  \
             font-weight: {};\n  font-style: {};\n  font-display: swap;\n}}\n",
            f.family,
            f.file,
            f.weight,
            if f.italic { "italic" } else { "normal" }
        );
    }

    let mut root: Vec<(String, String)> = Vec::new();
    for (family, fallback) in typography::FALLBACKS {
        let var = match family {
            typography::DISPLAY => "font-display",
            typography::DISPLAY_TEXT => "font-display-text",
            typography::MONO => "font-mono",
            _ => "font-ui",
        };
        root.push((var.into(), format!("\"{family}\", {fallback}")));
    }
    for (name, style) in typography::ALL {
        root.push((format!("text-{name}"), css_font(&style)));
        if style.tracking_em != 0.0 {
            root.push((
                format!("text-{name}-tracking"),
                format!("{}em", style.tracking_em),
            ));
        }
        if style.uppercase {
            root.push((format!("text-{name}-transform"), "uppercase".into()));
        }
    }
    for (k, v) in space::ALL {
        root.push((format!("space-{k}"), format!("{v}px")));
    }
    for (k, v) in radius::ALL {
        root.push((format!("radius-{k}"), format!("{v}px")));
    }
    root.push(("radius-checkbox".into(), "50%".into()));
    root.push(("hairline".into(), format!("{}px", elevation::HAIRLINE)));
    root.push(("focus-ring".into(), format!("{}px", elevation::FOCUS_RING)));
    root.push((
        "selection-bar".into(),
        format!("{}px", elevation::SELECTION_BAR),
    ));
    for (k, v) in motion::DURATIONS {
        root.push((format!("duration-{k}"), format!("{v}ms")));
    }
    for (k, e) in motion::EASINGS {
        root.push((format!("ease-{k}"), e.css()));
    }
    for (group, all) in [
        ("desktop", &desktop::ALL[..]),
        ("phone", &phone::ALL[..]),
        ("component", &component::ALL[..]),
    ] {
        for (k, v) in all {
            root.push((format!("{group}-{k}"), format!("{v}px")));
        }
    }
    for (k, v) in LANDSCAPE {
        let unit = if k.ends_with("opacity") { "" } else { "px" };
        root.push((format!("landscape-{k}"), format!("{v}{unit}")));
    }
    root.extend(chrome::COLORS.map(|(name, rgb)| (name.into(), rgb.hex())));
    root.extend(chrome::OPACITIES.map(|(name, alpha)| (name.into(), alpha.to_string())));
    css_block(&mut out, ":root", &root);

    for theme in Theme::ALL {
        let t = theme.key();
        css_block(
            &mut out,
            &format!("[data-theme=\"{t}\"]"),
            &[("shadow-overlay".into(), css_shadow(theme))],
        );
        for hue in hues::rooms() {
            let palette = palette(theme, hue.degrees);
            let mut vars = color_vars("color", palette.entries());
            vars.push((
                "overlay-scrim".into(),
                elevation::scrim(theme, palette.ink).css(),
            ));
            css_block(
                &mut out,
                &format!("[data-theme=\"{t}\"][data-room-hue=\"{}\"]", hue.key),
                &vars,
            );
        }
        for hue in hues::rooms() {
            css_block(
                &mut out,
                &format!(
                    "[data-theme=\"{t}\"] [data-list-hue=\"{k}\"],\n[data-theme=\"{t}\"][data-list-hue=\"{k}\"]",
                    k = hue.key
                ),
                &color_vars("list", list_colors(theme, hue.degrees).entries()),
            );
        }
        for hue in hues::AGENTS {
            css_block(
                &mut out,
                &format!(
                    "[data-theme=\"{t}\"] [data-agent=\"{k}\"],\n[data-theme=\"{t}\"][data-agent=\"{k}\"]",
                    k = hue.key
                ),
                &color_vars("agent", agent_colors(theme, hue.degrees).entries()),
            );
        }
    }
    for hue in hues::rooms() {
        css_block(
            &mut out,
            &format!("[data-room-hue=\"{}\"]", hue.key),
            &color_vars("dusk", dusk(hue.degrees).entries()),
        );
    }
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}

fn spec_json(spec: Spec) -> Value {
    match spec {
        Spec::Hued { l, c } => json!({ "l": l, "c": c }),
        Spec::Fixed(o) => json!({ "l": o.l, "c": o.c, "h": o.h }),
        Spec::Srgb(rgb) => json!(rgb.hex()),
    }
}

fn specs_json(specs: Vec<(&'static str, Spec, Spec)>) -> Value {
    let mut m = Map::new();
    for (name, light, dark) in specs {
        m.insert(
            name.into(),
            json!({ "light": spec_json(light), "dark": spec_json(dark) }),
        );
    }
    Value::Object(m)
}

fn colors_json(entries: Vec<(&'static str, Rgb)>) -> Value {
    Value::Object(
        entries
            .into_iter()
            .map(|(n, c)| (n.to_owned(), Value::String(c.hex())))
            .collect(),
    )
}

fn hues_json(hues: impl IntoIterator<Item = NamedHue>) -> Value {
    Value::Object(
        hues.into_iter()
            .map(|h| (h.key.to_owned(), json!(h.degrees)))
            .collect(),
    )
}

fn by_hue<T>(
    hues: impl IntoIterator<Item = NamedHue>,
    f: impl Fn(f64) -> T,
    entries: impl Fn(&T) -> Vec<(&'static str, Rgb)>,
) -> Value {
    Value::Object(
        hues.into_iter()
            .map(|h| (h.key.to_owned(), colors_json(entries(&f(h.degrees)))))
            .collect(),
    )
}

/// An `f32` as the JSON number it reads as (0.3, not 0.30000001192092896).
fn num(x: f32) -> Value {
    x.to_string()
        .parse::<f64>()
        .map(Value::from)
        .unwrap_or(Value::Null)
}

fn numbers_json(all: &[(&str, f32)]) -> Value {
    Value::Object(
        all.iter()
            .map(|(k, v)| ((*k).to_owned(), num(*v)))
            .collect(),
    )
}

fn rgba_json(c: Rgba) -> Value {
    json!({ "color": c.rgb.hex(), "alpha": num(c.alpha) })
}

/// `tokens.json`: the derivation specs, every precomputed colour, and every other token.
pub fn json() -> String {
    let mut colors = Map::new();
    for theme in Theme::ALL {
        colors.insert(
            theme.key().into(),
            json!({
                "rooms": by_hue(hues::rooms(), |h| palette(theme, h), Palette::entries),
                "lists": by_hue(hues::rooms(), |h| list_colors(theme, h), ListColors::entries),
                "agents": by_hue(hues::AGENTS, |h| agent_colors(theme, h), AgentColors::entries),
            }),
        );
    }
    colors.insert("dusk".into(), by_hue(hues::rooms(), dusk, Dusk::entries));

    let type_scale: Map<String, Value> = typography::ALL
        .iter()
        .map(|(name, s)| {
            (
                (*name).to_owned(),
                json!({
                    "family": s.family,
                    "size": num(s.size),
                    "lineHeight": num(s.line_height),
                    "weight": s.weight,
                    "italic": s.italic,
                    "trackingEm": num(s.tracking_em),
                    "uppercase": s.uppercase,
                    "tabular": s.tabular,
                }),
            )
        })
        .collect();

    let faces: Vec<Value> = fonts::FACES
        .iter()
        .map(|f| json!({ "family": f.family, "weight": f.weight, "italic": f.italic, "file": f.path() }))
        .collect();

    let shadow = |theme| -> Value {
        shadows(theme)
            .iter()
            .map(|s| json!({ "y": num(s.y), "blur": num(s.blur), "spread": num(s.spread), "color": rgba_json(s.color) }))
            .collect()
    };

    let mut radii = numbers_json(&radius::ALL);
    // Not a number: checkboxes and agent marks are circles (`CircleShape` in Compose).
    radii["checkbox"] = json!(radius::CHECKBOX);
    let doc = json!({
        "_comment": HEADER,
        "derivation": {
            "roomDarkHueShift": ROOM_DARK_HUE_SHIFT,
            "listDarkHueShift": LIST_DARK_HUE_SHIFT,
            "listOnStrongDark": { "l": LIST_ON_STRONG_DARK.0, "c": LIST_ON_STRONG_DARK.1 },
            "gamutMapping": "keep L and h, reduce chroma by a 24-step binary search until in sRGB (epsilon 1e-4); round half to even",
            "contrastGuards": {
                "step": GUARD_STEP,
                "rule": "after deriving a room palette, move each failing foreground's L away from its backgrounds in steps until every pair meets the minimum",
                "pairs": GUARDS.iter().map(|(fg, bgs, min)| json!({ "fg": fg, "bg": bgs, "min": min })).collect::<Vec<_>>(),
            },
            "room": specs_json(Palette::specs()),
            "list": specs_json(ListColors::specs()),
            "agent": specs_json(AgentColors::specs()),
            "dusk": specs_json(Dusk::specs()),
        },
        "hues": {
            "smartLists": hues_json(hues::SMART_LISTS),
            "swatches": hues_json(hues::SWATCHES),
            "agents": hues_json(hues::AGENTS),
        },
        "colors": colors,
        "chrome": {
            "colors": colors_json(chrome::COLORS.to_vec()),
            "opacities": numbers_json(&chrome::OPACITIES),
        },
        "fonts": { "faces": faces },
        "type": type_scale,
        "space": numbers_json(&space::ALL),
        "radius": radii,
        "elevation": {
            "hairline": num(elevation::HAIRLINE),
            "focusRing": num(elevation::FOCUS_RING),
            "selectionBar": num(elevation::SELECTION_BAR),
            "overlayShadow": { "light": shadow(Theme::Light), "dark": shadow(Theme::Dark) },
            "scrim": Theme::ALL.into_iter().map(|theme| {
                let rooms = hues::rooms().map(|hue| {
                    (hue.key.to_owned(), rgba_json(elevation::scrim(theme, palette(theme, hue.degrees).ink)))
                }).collect::<Map<_, _>>();
                (theme.key().to_owned(), Value::Object(rooms))
            }).collect::<Map<_, _>>(),
        },
        "motion": {
            "durationsMs": Value::Object(motion::DURATIONS.iter().map(|(k, v)| ((*k).to_owned(), json!(v))).collect()),
            "easings": Value::Object(motion::EASINGS.iter().map(|(k, e)| ((*k).to_owned(), json!([num(e.x1), num(e.y1), num(e.x2), num(e.y2)]))).collect()),
            "cues": numbers_json(&motion::CUES),
        },
        "metrics": {
            "desktop": numbers_json(&desktop::ALL),
            "phone": numbers_json(&phone::ALL),
            "component": numbers_json(&component::ALL),
        },
        "landscape": numbers_json(&LANDSCAPE),
        "icons": {
            "lucide": Icon::ALL.iter().map(|i| i.path()).collect::<Vec<_>>(),
            "glyphs": Glyph::ALL.iter().map(|g| g.path()).collect::<Vec<_>>(),
        },
    });
    let mut s = serde_json::to_string_pretty(&doc).unwrap_or_default();
    s.push('\n');
    s
}
