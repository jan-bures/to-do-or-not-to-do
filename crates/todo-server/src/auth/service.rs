/// Why authentication could not be initialized or owner recovery failed.
#[derive(Debug, thiserror::Error)]
pub enum AuthInitError {
    /// Storage failed.
    #[error(transparent)]
    Store(#[from] StoreError),
    /// The WebAuthn configuration was rejected.
    #[error("cannot configure passkeys for {origin}: {reason}")]
    Webauthn {
        /// The origin.
        origin: String,
        /// Why.
        reason: String,
    },
    /// Owner recovery requires an origin that can serve `/setup`.
    #[error("set public_origin in the server config before resetting the owner")]
    MissingOrigin,
    /// Refuse to create a database if the recovery command was pointed at the wrong directory.
    #[error("owner recovery requires an existing database at {}", .0.display())]
    MissingDatabase(PathBuf),
    /// A recovery path could not be resolved.
    #[error("cannot resolve recovery path {}: {source}", path.display())]
    RecoveryPath {
        /// The path that could not be resolved.
        path: PathBuf,
        /// Why.
        source: std::io::Error,
    },
    /// The setup code file could not be written.
    #[error("cannot write the setup code to {}: {source}", path.display())]
    SetupFile {
        /// The file.
        path: std::path::PathBuf,
        /// Why.
        source: std::io::Error,
    },
    /// No randomness.
    #[error(transparent)]
    Random(#[from] RandomError),
}

fn lock<T>(m: &Mutex<T>) -> MutexGuard<'_, T> {
    m.lock().unwrap_or_else(PoisonError::into_inner)
}

fn internal<E: std::fmt::Display>(what: &'static str) -> impl FnOnce(E) -> ApiError {
    move |e| {
        tracing::error!(error = %e, "{what}");
        ApiError::internal()
    }
}

impl From<RandomError> for ApiError {
    fn from(e: RandomError) -> Self {
        tracing::error!(error = %e, "no randomness");
        Self::internal()
    }
}

/// The error for a ceremony that failed verification (generic on purpose).
fn ceremony_failed() -> ApiError {
    ApiError::new(
        StatusCode::UNAUTHORIZED,
        "verification_failed",
        "the passkey could not be verified; try again",
    )
}

fn locked_out(secs: u32) -> ApiError {
    ApiError::new(
        StatusCode::TOO_MANY_REQUESTS,
        "locked_out",
        "too many failed attempts; try again later",
    )
    .with_retry_after(secs)
}

