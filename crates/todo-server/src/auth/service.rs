    /// Creates an agent token and returns its row ID and the token (shown once). Blocking.
    pub fn create_agent(
        &self,
        agent: &AgentId,
        default: AccessLevel,
        writes_per_hour: Option<u32>,
        expires_in_days: Option<u32>,
        ip: Option<IpAddr>,
    ) -> Result<(i64, String), ApiError> {
        if agent.as_str() == ASSISTANT_AGENT_ID {
            return Err(ApiError::new(
                StatusCode::CONFLICT,
                "reserved_agent",
                "this identity is reserved for the in-app assistant",
            ));
        }
        let token = format!("{AGENT_TOKEN_PREFIX}{}", secret::random_token::<32>()?);
        let wph = writes_per_hour
            .unwrap_or(self.cfg.agent_writes_per_hour)
            .max(1);
        let now = self.now();
        let expires_at = expires_in_days.map(|d| now + i64::from(d) * 86_400_000);
        let grants = Grants::with_default(default);
        let guard = self.begin_mutation();
        let Some(id) = self.store.add_agent(
            agent,
            &secret::digest_hex(&token),
            &grants,
            wph,
            expires_at,
            now,
        )?
        else {
            return Err(ApiError::new(
                StatusCode::CONFLICT,
                "agent_exists",
                "this agent already has an active token; revoke it first",
            ));
        };
        self.publish(&guard)?;
        drop(guard);
        self.audit(
            audit::AGENT_TOKEN_CREATED,
            ip,
            json!({ "agent": agent, "token_id": id, "default": default, "writes_per_hour": wph, "expires_at": expires_at }),
        );
        Ok((id, token))
    }

    /// Revokes an agent token, immediately. Blocking.
    pub fn revoke_agent(&self, id: i64, by: impl Into<Who>) -> Result<bool, ApiError> {
        let by = by.into();
        let guard = self.begin_mutation();
        let row = self.store.agent(id)?;
        let entry = self.audit_entry(
            audit::AGENT_TOKEN_REVOKED,
            by,
            json!({ "agent": row.map(|r| r.agent), "token_id": id }),
        );
        if !self.store.revoke_agent(id, self.now(), &entry)? {
            return Ok(false);
        }
        self.quotas.forget(id);
        self.publish(&guard)?;
        drop(guard);
        self.revoked();
        Ok(true)
    }

    /// Replaces an agent's grants. Blocking.
    pub fn set_grants(
        &self,
        id: i64,
        grants: &Grants,
        by: impl Into<Who>,
    ) -> Result<bool, ApiError> {
        let by = by.into();
        let guard = self.begin_mutation();
        let Some(before) = self.store.agent(id)? else {
            return Ok(false);
        };
        let entry = self.audit_entry(
            audit::GRANTS_CHANGED,
            by,
            json!({ "agent": before.agent, "token_id": id, "before": before.grants, "after": grants }),
        );
        if !self.store.set_agent_grants(id, grants, &entry)? {
            return Ok(false);
        }
        self.publish(&guard)?;
        drop(guard);
        self.revoked();
        Ok(true)
    }

    /// Replaces an active agent token's grants and write quota together. Returns false if there is
    /// no such active token. Blocking.
    pub fn set_agent_access(
        &self,
        id: i64,
        grants: &Grants,
        writes_per_hour: u32,
        by: impl Into<Who>,
    ) -> Result<bool, ApiError> {
        let by = by.into();
        let writes_per_hour = writes_per_hour.max(1);
        let guard = self.begin_mutation();
        let Some(before) = self.store.agent(id)?.filter(|a| a.revoked_at.is_none()) else {
            return Ok(false);
        };
        let entry = self.audit_entry(
            audit::GRANTS_CHANGED,
            by,
            json!({
                "agent": before.agent,
                "token_id": id,
                "before": before.grants,
                "after": grants,
                "writes_per_hour_before": before.writes_per_hour,
                "writes_per_hour_after": writes_per_hour,
            }),
        );
        if !self
            .store
            .set_agent_access(id, grants, writes_per_hour, &entry)?
        {
            return Ok(false);
        }
        self.publish(&guard)?;
        drop(guard);
        self.revoked();
        Ok(true)
    }

