    fn snapshot(&self) -> Arc<Snapshot> {
        self.snapshot
            .read()
            .unwrap_or_else(PoisonError::into_inner)
            .clone()
    }

    /// Takes the mutation lock (see [`AuthService::publish`]).
    fn begin_mutation(&self) -> MutexGuard<'_, ()> {
        lock(&self.mutations)
    }

    /// The next publish signals after updating the engine, then waits for the resume sender to drop.
    #[cfg(test)]
    pub(crate) fn pause_next_publish(
        &self,
    ) -> (
        tokio::sync::oneshot::Receiver<()>,
        std::sync::mpsc::Sender<()>,
    ) {
        let (paused, reached) = tokio::sync::oneshot::channel();
        let (release, resume) = std::sync::mpsc::channel();
        *lock(&self.pause_next_publish) = Some(PublishPause { paused, resume });
        (reached, release)
    }

    /// Reloads device and agent tokens from the store and publishes them with the grants.
    pub fn reload_bearers(&self) -> Result<(), StoreError> {
        let guard = self.begin_mutation();
        self.publish(&guard)
    }

    /// Reads the valid tokens and grants from the store and publishes them: first the grants to the
    /// engine (whose state decides commands and visibility), then one swap of the snapshot that
    /// authentication and [`standing`](Self::standing) read. In that order, a standing never shows
    /// grants the engine does not filter with yet: an event stream that starts during a publish
    /// records the old standing (and ends at the swap) or the new one (and filters with the new
    /// grants). Runs only under the mutation lock (`_held`), which every change to devices, agents
    /// and grants holds from its write until here; so publishes happen in write order and none can
    /// bring back a token revoked after it read the store.
    fn publish(&self, _held: &MutexGuard<'_, ()>) -> Result<(), StoreError> {
        let mut map = HashMap::new();
        for d in self.store.devices()? {
            if d.revoked_at.is_some() {
                continue;
            }
            if let Some(h) = crate::config::decode_hash(&d.token_hash) {
                map.insert(
                    h,
                    BearerEntry {
                        kind: BearerKind::Device(d.id),
                        last_touch: AtomicI64::new(d.last_used_at.unwrap_or(0)),
                    },
                );
            }
        }
        let mut grants = BTreeMap::new();
        for a in self.store.agents()? {
            // A database from an older deployment might already contain this once-valid slug.
            if a.revoked_at.is_some() || a.agent.as_str() == ASSISTANT_AGENT_ID {
                continue;
            }
            if let Some(h) = crate::config::decode_hash(&a.token_hash) {
                grants.insert(a.agent.clone(), a.grants.clone());
                map.insert(
                    h,
                    BearerEntry {
                        kind: BearerKind::Agent {
                            token: a.id,
                            agent: a.agent,
                            writes_per_hour: a.writes_per_hour,
                            expires_at: a.expires_at,
                        },
                        last_touch: AtomicI64::new(a.last_used_at.unwrap_or(0)),
                    },
                );
            }
        }
        self.engine.set_grants(grants.clone());
        #[cfg(test)]
        {
            let pause = lock(&self.pause_next_publish).take();
            if let Some(pause) = pause {
                let _ = pause.paused.send(());
                let _ = pause.resume.recv();
            }
        }
        *self
            .snapshot
            .write()
            .unwrap_or_else(PoisonError::into_inner) = Arc::new(Snapshot {
            bearers: map,
            grants,
        });
        Ok(())
    }

    /// Wakes event streams to re-check their caller (see [`standing`](Self::standing)).
    fn revoked(&self) {
        self.revocations.send_modify(|n| *n = n.wrapping_add(1));
    }

    /// Changes whenever a token is revoked or grants change; event streams re-check their caller.
    #[must_use]
    pub fn revocations(&self) -> watch::Receiver<u64> {
        self.revocations.subscribe()
    }

    /// What `principal` may do now: `None` once its token is revoked or expired; otherwise, for an
    /// agent, its current grants. An event stream compares this with what it started with and closes
    /// on any change, so frames filtered under older grants are never delivered.
    #[must_use]
    pub fn standing(&self, principal: &Principal) -> Option<Standing> {
        if !self.is_active(principal) {
            return None;
        }
        Some(Standing(match principal {
            Principal::Owner { .. } | Principal::Session { .. } => None,
            Principal::Agent { agent, .. } => self.snapshot().grants.get(agent).cloned(),
        }))
    }

    /// True while `principal` may still use the API (its token is neither revoked nor expired, or its
    /// session has not ended).
    ///
    /// For a session this reads the store (one indexed row); it is called when a stream starts, on
    /// revocation notices and at heartbeats, never per event.
    #[must_use]
    pub fn is_active(&self, principal: &Principal) -> bool {
        if let Principal::Session { session, .. } = principal {
            return self.session_live(session);
        }
        let now = self.now();
        let found = self
            .snapshot()
            .bearers
            .values()
            .any(|e| match (&e.kind, principal) {
                (BearerKind::Device(d), Principal::Owner { device }) => d == device,
                (
                    BearerKind::Agent {
                        token, expires_at, ..
                    },
                    Principal::Agent { token: t, .. },
                ) => token == t && expires_at.is_none_or(|x| x > now),
                _ => false,
            });
        found
            || matches!((principal, &self.owner_tokens), (Principal::Owner { device }, Some(t)) if t.has_device(device))
    }

    /// Records that `principal` used its token (written at most once a minute, off the request path).
    pub fn note_use(self: &Arc<Self>, principal: &Principal) {
        let now = self.now();
        let snapshot = self.snapshot();
        let due = snapshot.bearers.values().find_map(|e| {
            let matches = match (&e.kind, principal) {
                (BearerKind::Device(d), Principal::Owner { device }) => d == device,
                (BearerKind::Agent { token, .. }, Principal::Agent { token: t, .. }) => token == t,
                _ => false,
            };
            (matches && now - e.last_touch.load(Ordering::Relaxed) >= TOUCH_INTERVAL_MS).then(
                || {
                    e.last_touch.store(now, Ordering::Relaxed);
                },
            )
        });
        if due.is_none() {
            return;
        }
        let svc = self.clone();
        let principal = principal.clone();
        tokio::task::spawn_blocking(move || {
            let r = match &principal {
                Principal::Owner { device } => svc.store.touch_device(device.as_str(), now),
                Principal::Agent { token, .. } => svc.store.touch_agent(*token, now),
                // Never due: sessions have no bearer entry (they are touched by their own lookup).
                Principal::Session { .. } => Ok(()),
            };
            if let Err(e) = r {
                tracing::warn!(error = %e, "cannot record token use");
            }
        });
    }

    /// Whether `ip` may still try bearer authentication (see `bearer_failures`); `Err` carries the
    /// seconds to wait.
    pub fn bearer_admission(&self, ip: Option<IpAddr>) -> Result<(), u32> {
        ip.map_or(Ok(()), |ip| self.bearer_failures.peek(&ip))
    }

    /// Records a failed bearer authentication from `ip`, auditing bursts.
    pub fn bearer_failed(self: &Arc<Self>, ip: Option<IpAddr>) {
        if let Some(ip) = ip {
            // Spending fails once the budget is empty; the next request is turned away earlier.
            let _ = self.bearer_failures.check(&ip);
        }
        if let Some(n) = self.bearer_failure_bursts.hit() {
            tracing::warn!(failures = n, "burst of failed API authentications");
            let svc = self.clone();
            tokio::task::spawn_blocking(move || {
                svc.audit(
                    audit::AUTH_FAILURE_BURST,
                    None,
                    json!({ "failures_last_minute": n, "source": "bearer" }),
                );
            });
        }
    }

