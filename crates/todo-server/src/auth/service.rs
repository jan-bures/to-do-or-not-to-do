    /// True once the owner has registered a passkey.
    pub fn owner_ready(&self) -> Result<bool, StoreError> {
        Ok(self.store.meta(META_OWNER_READY)?.is_some())
    }

    /// Removes the setup code file, if any.
    fn remove_setup_file(&self) {
        match std::fs::remove_file(&self.setup_file) {
            Ok(()) => tracing::info!("removed the setup code file"),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => {
                tracing::warn!(error = %e, path = %self.setup_file.display(), "cannot remove the setup code file")
            }
        }
    }

    /// Writes the code to the setup file, readable only by the account running the server.
    fn write_setup_file(
        path: &std::path::Path,
        code: &str,
        origin: &PublicOrigin,
    ) -> Result<(), AuthInitError> {
        use std::io::Write as _;
        let write = || -> std::io::Result<()> {
            match std::fs::remove_file(path) {
                Ok(()) => {}
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
                Err(e) => return Err(e),
            }
            let mut f = todo_fs::create_private_file(path)?;
            writeln!(
                f,
                "{code}\n\nOne-time owner setup code: open {}/setup and enter it within 15 minutes of the \
             server start (and within 24 hours of reset for a code created offline). It works once; \
             this file is deleted when setup is done. Restart the server for a new code.",
                origin.as_str()
            )?;
            f.sync_all()
        };
        write().map_err(|source| AuthInitError::SetupFile {
            path: path.to_owned(),
            source,
        })
    }

    fn fresh_setup_code() -> Result<String, RandomError> {
        Ok(secret::random_code(SETUP_CODE_LEN)?
            .as_bytes()
            .chunks(5)
            .map(|c| String::from_utf8_lossy(c).into_owned())
            .collect::<Vec<_>>()
            .join("-"))
    }

    /// Offline recovery. The database ownership lock excludes any running server, so there are no
    /// live pairings or invites. Leaves the new code in the same owner-only file as first setup.
    pub fn reset_owner(
        config: &Config,
        revoke_agents: bool,
        revoke_shares: bool,
    ) -> Result<OwnerResetReport, AuthInitError> {
        let origin = config
            .origin()
            .map_err(|e| AuthInitError::Webauthn {
                origin: config.public_origin.clone().unwrap_or_default(),
                reason: e.to_string(),
            })?
            .ok_or(AuthInitError::MissingOrigin)?;
        let path = config.database_path();
        if !path.is_file() {
            return Err(AuthInitError::MissingDatabase(path));
        }
        let canonicalize = |path: &Path| {
            std::fs::canonicalize(path).map_err(|source| AuthInitError::RecoveryPath {
                path: path.to_owned(),
                source,
            })
        };
        let database = canonicalize(&path)?;
        let setup_file = canonicalize(&config.data_dir)?.join(SETUP_CODE_FILE);
        let _owner = crate::db::lock_database(&database)?;
        // Do not recreate the file even if it disappeared between the check and taking the lock.
        let mut conn = crate::db::open_existing_writer(&database)?;
        let code = Self::fresh_setup_code()?;
        let hash = secret::digest_hex(&secret::normalize_code(&code));
        let counts = super::store::reset_owner(
            &mut conn,
            &hash,
            jiff::Timestamp::now().as_millisecond(),
            revoke_agents,
            revoke_shares,
        )?;
        Self::write_setup_file(&setup_file, &code, &origin)?;
        Ok(OwnerResetReport {
            database,
            setup_file,
            counts,
        })
    }

    fn init_setup(&self, sink: Option<SetupCodeSink>) -> Result<(), AuthInitError> {
        // Always consume the offline hash on the first start, even if /setup is unavailable.
        let recovery = self.store.take_meta(META_RECOVERY_CODE)?;
        if self.owner_ready()? {
            self.remove_setup_file();
            return Ok(());
        }
        let Some(origin) = &self.origin else {
            self.remove_setup_file();
            tracing::warn!(
                "no owner passkey yet and no public_origin configured; set public_origin to enable /setup"
            );
            return Ok(());
        };
        // Use the offline code only before its deadline and if the owner-only file matches the
        // hash. Missing, mismatched and legacy untimestamped codes all rotate on startup.
        let now = self.now();
        let online_deadline = now + SETUP_CODE_TTL_MS;
        let recovered = recovery.and_then(|record| {
            let (reset_at, hash) = record.split_once(':')?;
            let reset_at = reset_at.parse::<i64>().ok()?;
            let deadline = reset_at.checked_add(RECOVERY_CODE_TTL_MS)?;
            if reset_at > now || deadline <= now {
                return None;
            }
            let contents = todo_fs::read_private_file(&self.setup_file, 4096).ok()?;
            let shown = std::str::from_utf8(&contents).ok()?.lines().next()?;
            (secret::digest_hex(&secret::normalize_code(shown)) == hash)
                .then(|| (shown.to_owned(), deadline.min(online_deadline)))
        });
        let (shown, expires_at) = match recovered {
            Some(code) => code,
            None => (Self::fresh_setup_code()?, online_deadline),
        };
        // Never logged: whoever reads a forwarded log could enrol their own passkey first.
        Self::write_setup_file(&self.setup_file, &shown, origin)?;
        *lock(&self.setup) = Some(SetupCode {
            hash: secret::digest(&secret::normalize_code(&shown)),
            expires_at,
            used: false,
        });
        tracing::warn!(path = %self.setup_file.display(), "owner setup: a one-time code for /setup is waiting in this file");
        if let Some(s) = sink {
            s(&shown);
        }
        Ok(())
    }

    /// True while `/setup` exists: no owner passkey yet and passkeys are configured.
    pub fn setup_open(&self) -> Result<bool, StoreError> {
        Ok(self.webauthn.is_some() && !self.owner_ready()?)
    }

    fn check_setup_code(&self, code: &str, now: i64) -> Result<(), &'static str> {
        let guard = lock(&self.setup);
        let Some(s) = guard.as_ref() else {
            return Err("no_code");
        };
        if s.used || s.expires_at <= now {
            return Err("expired");
        }
        // Wrong guesses never invalidate the code (that would let anyone block setup); they count
        // as sign-in failures of their address, which is locked out after a few (see `setup_start`).
        // With about 99 bits, guessing is hopeless anyway.
        let typed = secret::normalize_code(code);
        if secret::ct_eq(&secret::digest(&typed), &s.hash) {
            Ok(())
        } else {
            Err("wrong")
        }
    }

    fn owner_user_id(&self) -> Result<Uuid, ApiError> {
        if let Some(v) = self.store.meta(META_OWNER_USER)?
            && let Ok(u) = v.parse()
        {
            return Ok(u);
        }
        let u = Uuid::new_v4();
        self.store.set_meta(META_OWNER_USER, &u.to_string())?;
        Ok(u)
    }

    fn registration_options(&self) -> Result<(Value, PasskeyRegistration), ApiError> {
        let exclude: Vec<_> = self
            .store
            .passkeys()?
            .iter()
            .map(|p| p.passkey.cred_id().clone())
            .collect();
        let user = self.owner_user_id()?;
        let (ccr, reg) = self
            .webauthn()?
            .start_passkey_registration(
                user,
                "owner",
                "Owner",
                (!exclude.is_empty()).then_some(exclude),
            )
            .map_err(internal("cannot start passkey registration"))?;
        Ok((resident_key_preferred(&ccr)?, reg))
    }

    fn put_ceremony(
        &self,
        kind: &str,
        session: Option<&str>,
        state: &impl serde::Serialize,
    ) -> Result<String, ApiError> {
        let handle = secret::random_token::<16>()?;
        let now = self.now();
        let state = serde_json::to_string(state).map_err(internal("cannot encode ceremony"))?;
        self.store.put_ceremony(
            &secret::digest_hex(&handle),
            kind,
            session,
            &state,
            now + CEREMONY_TTL_MS,
            now,
        )?;
        Ok(handle)
    }

    fn take_ceremony<T: serde::de::DeserializeOwned>(
        &self,
        handle: &str,
        kind: &str,
        session: Option<&str>,
    ) -> Result<Option<T>, ApiError> {
        let Some(state) =
            self.store
                .take_ceremony(&secret::digest_hex(handle), kind, session, self.now())?
        else {
            return Ok(None);
        };
        serde_json::from_str(&state)
            .map(Some)
            .map_err(internal("cannot decode ceremony"))
    }

    /// Checks the setup code and starts registering the first passkey. Blocking.
    pub fn setup_start(&self, code: &str, ip: Option<IpAddr>) -> Result<(String, Value), ApiError> {
        if !self.setup_open()? {
            return Err(ApiError::not_found("no such page"));
        }
        self.check_lockout(ip)?;
        if let Err(why) = self.check_setup_code(code, self.now()) {
            self.record_failure(audit::SETUP_CODE_REJECTED, ip, json!({ "reason": why }));
            return Err(ApiError::new(
                StatusCode::UNAUTHORIZED,
                "invalid_setup_code",
                "the setup code is wrong, expired or used; restart the server for a new one if needed",
            ));
        }
        let (options, reg) = self.registration_options()?;
        let handle = self.put_ceremony("setup", None, &reg)?;
        Ok((handle, options))
    }

    /// Finishes registering the first passkey, consumes the setup code and signs the owner in.
    /// Blocking.
    pub fn setup_finish(
        &self,
        handle: &str,
        credential: &RegisterPublicKeyCredential,
        ip: Option<IpAddr>,
    ) -> Result<NewSession, ApiError> {
        if !self.setup_open()? {
            return Err(ApiError::not_found("no such page"));
        }
        let Some(reg) = self.take_ceremony::<PasskeyRegistration>(handle, "setup", None)? else {
            return Err(ceremony_expired());
        };
        let passkey = match self
            .webauthn()?
            .finish_passkey_registration(credential, &reg)
        {
            Ok(p) => p,
            Err(e) => {
                tracing::debug!(error = %e, "setup registration failed");
                self.record_failure(audit::SIGN_IN_FAILED, ip, json!({ "stage": "setup" }));
                return Err(ceremony_failed());
            }
        };
        {
            // Consume the code; a second ceremony started with the same code fails here.
            let mut guard = lock(&self.setup);
            match guard.as_mut() {
                Some(s) if !s.used && s.expires_at > self.now() => s.used = true,
                _ => return Err(ceremony_expired()),
            }
        }
        let now = self.now();
        let id = self
            .store
            .add_passkey("First passkey", &passkey, now, &CredentialOrigin::default())?
            .ok_or_else(ApiError::internal)?;
        self.store.set_meta(META_OWNER_READY, "1")?;
        self.remove_setup_file();
        self.audit(audit::SETUP_COMPLETED, ip, json!({}));
        tracing::info!("owner passkey registered; /setup is now closed");
        self.new_session(id)
    }

    // ---- sign-in, step-up, more passkeys ----------------------------------------------------------

    fn authentication_options(
        &self,
    ) -> Result<(RequestChallengeResponse, PasskeyAuthentication), ApiError> {
        let creds: Vec<Passkey> = self
            .store
            .passkeys()?
            .into_iter()
            .map(|p| p.passkey)
            .collect();
        if creds.is_empty() {
            return Err(ApiError::new(
                StatusCode::CONFLICT,
                "not_set_up",
                "no passkey is registered yet; finish /setup first",
            ));
        }
        self.webauthn()?
            .start_passkey_authentication(&creds)
            .map_err(internal("cannot start passkey authentication"))
    }

    /// Verifies an assertion, saves the new counter, and identifies the verifying passkey.
    fn verify_assertion(
        &self,
        state: &PasskeyAuthentication,
        credential: &PublicKeyCredential,
    ) -> Result<Option<i64>, ApiError> {
        let result = match self
            .webauthn()?
            .finish_passkey_authentication(credential, state)
        {
            Ok(r) => r,
            Err(e) => {
                tracing::debug!(error = %e, "passkey assertion rejected");
                return Ok(None);
            }
        };
        if !result.user_verified() {
            return Ok(None);
        }
        let now = self.now();
        for mut row in self.store.passkeys()? {
            if row.passkey.cred_id() == result.cred_id() {
                // Counter and backup flags (webauthn-rs already rejected a counter that went back).
                row.passkey.update_credential(&result);
                self.store.update_passkey(row.id, &row.passkey, now)?;
                return Ok(Some(row.id));
            }
        }
        Ok(None)
    }

    /// Starts a sign-in. Blocking.
    pub fn login_start(
        &self,
        ip: Option<IpAddr>,
    ) -> Result<(String, RequestChallengeResponse), ApiError> {
        self.webauthn()?;
        self.check_lockout(ip)?;
        let (rcr, state) = self.authentication_options()?;
        let handle = self.put_ceremony("login", None, &state)?;
        Ok((handle, rcr))
    }

    /// Finishes a sign-in and creates a session. Blocking.
    pub fn login_finish(
        &self,
        handle: &str,
        credential: &PublicKeyCredential,
        ip: Option<IpAddr>,
    ) -> Result<NewSession, ApiError> {
        self.check_lockout(ip)?;
        let Some(state) = self.take_ceremony::<PasskeyAuthentication>(handle, "login", None)?
        else {
            self.record_failure(
                audit::SIGN_IN_FAILED,
                ip,
                json!({ "reason": "unknown_ceremony" }),
            );
            return Err(ceremony_expired());
        };
        let guard = self.begin_mutation();
        let Some(id) = self.verify_assertion(&state, credential)? else {
            self.record_failure(audit::SIGN_IN_FAILED, ip, json!({ "reason": "assertion" }));
            return Err(ceremony_failed());
        };
        let session = self.new_session(id)?;
        drop(guard);
        if let Some(ip) = ip {
            self.failures.succeed(&ip);
        }
        self.audit(audit::SIGN_IN, ip, json!({}));
        Ok(session)
    }

    /// Starts a step-up for a session. Blocking.
    pub fn step_up_start(
        &self,
        session: &SessionRow,
    ) -> Result<(String, RequestChallengeResponse), ApiError> {
        let (rcr, state) = self.authentication_options()?;
        let handle = self.put_ceremony("step_up", Some(&session.id_hash), &state)?;
        Ok((handle, rcr))
    }

    /// Finishes a step-up: the session counts as freshly verified. Blocking.
    pub fn step_up_finish(
        &self,
        session: &SessionRow,
        handle: &str,
        credential: &PublicKeyCredential,
        ip: Option<IpAddr>,
    ) -> Result<(), ApiError> {
        let Some(state) =
            self.take_ceremony::<PasskeyAuthentication>(handle, "step_up", Some(&session.id_hash))?
        else {
            return Err(ceremony_expired());
        };
        let guard = self.begin_mutation();
        if !self.session_live(&session.id_hash) {
            return Err(ApiError::unauthorized());
        }
        let Some(id) = self.verify_assertion(&state, credential)? else {
            self.record_failure(audit::STEP_UP_FAILED, ip, json!({}));
            return Err(ceremony_failed());
        };
        self.store.set_verified(&session.id_hash, self.now(), id)?;
        drop(guard);
        self.audit(audit::STEP_UP, ip, json!({}));
        Ok(())
    }

    /// Starts registering another passkey (needs a fresh step-up). Blocking.
    pub fn passkey_add_start(&self, session: &SessionRow) -> Result<(String, Value), ApiError> {
        self.require_step_up(session)?;
        let (options, reg) = self.registration_options()?;
        let handle = self.put_ceremony("add_passkey", Some(&session.id_hash), &reg)?;
        Ok((handle, options))
    }

    /// Finishes registering another passkey. Blocking.
    pub fn passkey_add_finish(
        &self,
        session: &SessionRow,
        handle: &str,
        credential: &RegisterPublicKeyCredential,
        name: &str,
        ip: Option<IpAddr>,
    ) -> Result<(), ApiError> {
        self.require_step_up(session)?;
        let Some(reg) = self.take_ceremony::<PasskeyRegistration>(
            handle,
            "add_passkey",
            Some(&session.id_hash),
        )?
        else {
            return Err(ceremony_expired());
        };
        let passkey = self
            .webauthn()?
            .finish_passkey_registration(credential, &reg)
            .map_err(|e| {
                tracing::debug!(error = %e, "passkey registration failed");
                ceremony_failed()
            })?;
        let name = clean_label(name, "Passkey");
        let guard = self.begin_mutation();
        if !self.session_live(&session.id_hash) {
            return Err(ApiError::unauthorized());
        }
        let origin = self
            .store
            .session_origin(&session.id_hash)?
            .ok_or_else(ApiError::unauthorized)?;
        if self
            .store
            .add_passkey(&name, &passkey, self.now(), &origin)?
            .is_none()
        {
            return Err(ApiError::new(
                StatusCode::CONFLICT,
                "already_registered",
                "this passkey is already registered",
            ));
        }
        drop(guard);
        self.audit(audit::PASSKEY_ADDED, ip, json!({ "name": name }));
        Ok(())
    }

    pub(crate) fn revoke_passkey(
        &self,
        session: &SessionRow,
        id: i64,
        ip: Option<IpAddr>,
    ) -> Result<(), ApiError> {
        if !self.revoke_credentials(
            CredentialRoot::Passkey(id),
            Revoker::Session(session),
            ip.into(),
        )? {
            return Err(ApiError::not_found("no such passkey"));
        }
        Ok(())
    }

    pub(crate) fn paired_device(&self, device: &DeviceId, headers: &HeaderMap) -> bool {
        bearer(headers).ok().is_some_and(|token| {
            self.snapshot()
                .bearers
                .get(&secret::digest(token))
                .is_some_and(|entry| matches!(&entry.kind, BearerKind::Device(id) if id == device))
        })
    }

    fn issuer_origin(
        &self,
        issuer: Option<&super::invite::Issuer>,
        gone: fn() -> ApiError,
    ) -> Result<CredentialOrigin, ApiError> {
        match issuer {
            Some(super::invite::Issuer::Session(session)) => {
                self.store.session_origin(session)?.ok_or_else(gone)
            }
            // The direct device, if any, is already in `issued_by`.
            _ => Ok(CredentialOrigin::default()),
        }
    }

    pub(crate) fn invite_issuer_live(&self, issuer: &super::invite::Issuer) -> bool {
        match issuer {
            super::invite::Issuer::Device(device) => self
                .snapshot()
                .bearers
                .values()
                .any(|entry| matches!(&entry.kind, BearerKind::Device(id) if id == device)),
            super::invite::Issuer::Session(session) => self.session_live(session),
        }
    }

    pub(crate) fn invite_passkey_start(
        &self,
        secret: &str,
        name: String,
    ) -> Result<(String, Value), ApiError> {
        let issuer = self
            .invites
            .browser_issuer(secret, self.now())
            .ok_or_else(crate::api::invite::invite_gone)?;
        if !self.invite_issuer_live(&issuer) || self.setup_open()? {
            return Err(crate::api::invite::invite_gone());
        }
        let (options, registration) = self.registration_options()?;
        let handle = self
            .invites
            .start_browser(secret, registration, name, self.now())?
            .ok_or_else(crate::api::invite::invite_gone)?;
        Ok((handle, options))
    }

    pub(crate) fn invite_passkey_finish(
        &self,
        handle: &str,
        credential: &RegisterPublicKeyCredential,
        ip: Option<IpAddr>,
    ) -> Result<NewSession, ApiError> {
        let (id, registration, name) = self
            .invites
            .take_browser(handle, self.now())
            .ok_or_else(ceremony_expired)?;
        let passkey = self
            .webauthn()?
            .finish_passkey_registration(credential, &registration)
            .map_err(|_| ceremony_failed())?;
        let claim = self
            .invites
            .claim_browser(&id, self.now())
            .ok_or_else(crate::api::invite::invite_gone)?;
        let result = (|| {
            let guard = self.begin_mutation();
            if !self.invite_issuer_live(&claim.issuer) {
                return Err(crate::api::invite::invite_gone());
            }
            let mut session = self.new_session_values()?;
            // Registration is not an assertion. This browser must verify again before step-up actions.
            session.row.verified_at = super::store::UNVERIFIED_AT;
            if !self.store.add_passkey_with_session(
                &name,
                &passkey,
                &session.row,
                &claim.issuer.label(),
                &self.issuer_origin(Some(&claim.issuer), crate::api::invite::invite_gone)?,
            )? {
                return Err(ApiError::new(
                    StatusCode::CONFLICT,
                    "already_registered",
                    "this passkey is already registered",
                ));
            }
            drop(guard);
            self.audit(
                audit::PASSKEY_ADDED,
                ip,
                json!({ "name": name, "issuer": claim.issuer }),
            );
            Ok(session)
        })();
        self.invites
            .finish(&claim, result.as_ref().ok().map(|_| name), self.now());
        result
    }

    // ---- sessions ---------------------------------------------------------------------------------

    fn new_session(&self, passkey_id: i64) -> Result<NewSession, ApiError> {
        let session = self.new_session_values()?;
        self.store.create_session(&session.row, passkey_id)?;
        Ok(session)
    }

    fn new_session_values(&self) -> Result<NewSession, ApiError> {
        let cookie = secret::random_token::<32>()?;
        let csrf = secret::random_token::<32>()?;
        let id_hash = secret::digest_hex(&cookie);
        let now = self.now();
        Ok(NewSession {
            cookie,
            row: SessionRow {
                id_hash,
                csrf,
                created_at: now,
                last_seen_at: now,
                verified_at: now,
            },
        })
    }

    fn idle_ms(&self) -> i64 {
        i64::try_from(self.cfg.session_idle_timeout_mins.saturating_mul(60_000)).unwrap_or(i64::MAX)
    }

    fn absolute_ms(&self) -> i64 {
        i64::try_from(
            self.cfg
                .session_absolute_timeout_hours
                .saturating_mul(3_600_000),
        )
        .unwrap_or(i64::MAX)
    }

    /// Seconds until a new session's absolute timeout (the cookie's `Max-Age`).
    #[must_use]
    pub fn session_max_age_secs(&self) -> i64 {
        self.absolute_ms() / 1000
    }

    /// The live session for a cookie value, recording the activity. Expired sessions are deleted.
    /// Blocking.
    pub fn session(&self, cookie: &str) -> Result<Option<SessionRow>, StoreError> {
        let row = self.peek_session(cookie)?;
        if let Some(row) = &row {
            self.touch_session(row)?;
        }
        Ok(row)
    }

    /// The live session for a cookie value **without** recording activity (expired sessions are
    /// still deleted). For callers that first check something else about the request, such as its
    /// CSRF token, and then call [`Self::touch_session`]. Blocking.
    pub fn peek_session(&self, cookie: &str) -> Result<Option<SessionRow>, StoreError> {
        let id_hash = secret::digest_hex(cookie);
        let Some(row) = self.store.session(&id_hash)? else {
            return Ok(None);
        };
        let now = self.now();
        if now - row.last_seen_at >= self.idle_ms() || now - row.created_at >= self.absolute_ms() {
            self.store.delete_session(&id_hash)?;
            return Ok(None);
        }
        Ok(Some(row))
    }

    /// Records activity on a session found by [`Self::peek_session`] (at most once a minute).
    /// Blocking.
    pub fn touch_session(&self, row: &SessionRow) -> Result<(), StoreError> {
        let now = self.now();
        if now - row.last_seen_at >= TOUCH_INTERVAL_MS {
            self.store.touch_session(&row.id_hash, now)?;
        }
        Ok(())
    }

    /// True if the session with this ID hash exists and has timed out neither way (does not touch it).
    #[must_use]
    pub fn session_live(&self, id_hash: &str) -> bool {
        match self.store.session(id_hash) {
            Ok(Some(row)) => {
                let now = self.now();
                now - row.last_seen_at < self.idle_ms() && now - row.created_at < self.absolute_ms()
            }
            Ok(None) => false,
            Err(e) => {
                tracing::error!(error = %e, "session check failed");
                false
            }
        }
    }

    /// Ends a session. Blocking.
    pub fn end_session(&self, session: &SessionRow, ip: Option<IpAddr>) -> Result<(), StoreError> {
        let guard = self.begin_mutation();
        self.store.delete_session(&session.id_hash)?;
        drop(guard);
        // The web app's event streams re-check their session and close.
        self.revoked();
        self.audit(audit::SIGN_OUT, ip, json!({}));
        let now = self.now();
        self.store
            .purge_sessions(now - self.idle_ms(), now - self.absolute_ms())
    }

    /// True if the session verified a passkey within [`STEP_UP_MS`].
    #[must_use]
    pub fn is_fresh(&self, session: &SessionRow) -> bool {
        session.verified_at != super::store::UNVERIFIED_AT
            && self.now() - session.verified_at < STEP_UP_MS
    }

    /// Fails with 403 `step_up_required` unless the session is fresh.
    pub fn require_step_up(&self, session: &SessionRow) -> Result<(), ApiError> {
        if self.is_fresh(session) {
            Ok(())
        } else {
            Err(step_up_required())
        }
    }

    /// Shares the wrong-code budget across both browser routes, and across addresses for each
    /// device. Sessions reset by signing in again; devices cool down after one pairing lifetime.
    pub(crate) fn look_up_pairing_code<T>(
        &self,
        issuer: super::invite::Issuer,
        lookup: impl FnOnce() -> Option<T>,
    ) -> Result<Option<T>, ApiError> {
        let mut attempts = lock(&self.code_lookups);
        let now = self.now();
        attempts.retain(|_, (_, expires)| *expires > now);
        if attempts
            .get(&issuer)
            .is_some_and(|(count, _)| *count >= MAX_CODE_LOOKUPS)
        {
            return Err(ApiError::new(
                StatusCode::TOO_MANY_REQUESTS,
                "too_many_codes",
                match issuer {
                    super::invite::Issuer::Session(_) => {
                        "too many wrong codes; sign out and in again to continue"
                    }
                    super::invite::Issuer::Device(_) => {
                        "too many wrong codes; wait five minutes to continue"
                    }
                },
            ));
        }
        let result = lookup();
        if result.is_none() {
            let expires = match issuer {
                super::invite::Issuer::Session(_) => now.saturating_add(self.absolute_ms()),
                super::invite::Issuer::Device(_) => now + super::pairing::PAIRING_TTL_MS,
            };
            let attempt = attempts.entry(issuer).or_insert((0, expires));
            attempt.0 += 1;
            attempt.1 = expires;
        }
        Ok(result)
    }

